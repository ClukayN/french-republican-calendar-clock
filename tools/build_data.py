def main():
    days_total = sum(len(m[4]) for m in MONTHS)
    assert days_total == 360, days_total
    for m in MONTHS:
        assert len(m[4]) == 30, (m[0], len(m[4]))

    out = {"months": [], "sansculottides": []}
    for fr, cn, season, note, days in MONTHS:
        out["months"].append({
            "fr": fr,
            "cn": cn,
            "season": season,
            "note": note,
            "days": [{"fr": d[0], "cn": d[1], "cat": d[2], "desc": d[3]} for d in days],
        })
    for fr, cn, cat, desc, date in SANSCULOTTIDES:
        out["sansculottides"].append({"fr": fr, "cn": cn, "cat": cat, "desc": desc, "date": date})

    js = "/* 法国共和历 · 366 日物产名录（法文名取自共和历法令，中文名取自中文维基百科） */\n"
    js += "window.CALENDAR_DATA = " + json.dumps(out, ensure_ascii=False, indent=1) + ";\n"
    dst = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "www", "data.js")
    with io.open(dst, "w", encoding="utf-8", newline="\n") as f:
        f.write(js)
    print("wrote", os.path.abspath(dst), len(js), "chars")
    print("months", len(out["months"]), "days", days_total, "complementary", len(out["sansculottides"]))

if __name__ == "__main__":
    main()
